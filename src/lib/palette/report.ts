/**
 * Markdown rendering of the registry's recorded validation (docs/PALETTES.md
 * §7). `node scripts/validate_palette.js --all` prints `renderValidationReport`
 * and the doc carries the output verbatim between its markers; a test diffs
 * the two so a pasted number can never rot (results are re-run, never
 * re-typed). Framework-free [R-PURE].
 */
import type { PaletteFamily } from './families';
import type { Palette } from './registry';
import { SURFACES } from './validate';

/** Markers around the generated block in PALETTES.md. */
export const REPORT_BEGIN = '<!-- validation:begin (generated by `node scripts/validate_palette.js --all`; do not edit) -->';
export const REPORT_END = '<!-- validation:end -->';

const yes = (b: boolean): string => (b ? 'yes' : 'no');
const pair = (p: [string, string] | null): string => (p ? ` ${p[0]}↔${p[1]}` : '');

/** One row per categorical set: separation, band, chroma, contrast and the two flags. */
export function categoricalTable(palettes: readonly Palette[]): string {
  const rows = palettes.filter((p) => p.kind === 'categorical').map((p) => {
    const v = p.validation.categorical!;
    const low = v.lowContrast[SURFACES[0]!] ?? [];
    const verdict = p.labelsRequired ? (v.cvdPass && v.normalPass ? 'labels by policy' : 'labels required') : 'passes';
    return `| \`${p.id}\` | ${p.family} | ${p.colors.length} | ${v.cvdWorst.toFixed(1)}${pair(v.cvdPair)} | ${v.normalWorst.toFixed(1)}${pair(v.normalPair)} | ${v.offBand.length} | ${v.lowChroma.length} | ${low.length} | ${yes(p.colorblindSafe)} | ${yes(p.labelsRequired)} | ${verdict} |`;
  });
  return [
    `| Set | Family | n | CVD adjacent (worst) | Normal-vision (worst) | Off band | Low chroma | Contrast < 3:1 (${SURFACES[0]}) | CVD-safe | Labels required | Verdict |`,
    '|---|---|---|---|---|---|---|---|---|---|---|',
    ...rows,
  ].join('\n');
}

/**
 * Verdict of a ramp row. Sequential ramps take the full ordinal gate; a
 * diverging ramp passes on monotone arms with a visible step gap, because its
 * neutral midpoint (L 0.90) sits near the surface by design (§2.3) and fails
 * the light-end check on purpose.
 */
export function rampVerdict(p: Palette): string {
  const r = p.validation.ramp!;
  if (r.exempt) return 'exempt (parity)';
  if (p.kind === 'diverging') return r.monotone && r.minDeltaL >= 0.06 ? 'arms pass' : 'flagged';
  return r.ok ? 'passes' : 'flagged';
}

/** One row per ramp (stepped form; both arms for diverging): monotone, step gap, light end, hue spread. */
export function rampTable(palettes: readonly Palette[]): string {
  const rows = palettes.filter((p) => p.kind !== 'categorical').map((p) => {
    const r = p.validation.ramp!;
    const light = SURFACES.map((s) => `${(r.lightEnd[s] ?? 0).toFixed(2)}`).join(' / ');
    const verdict = rampVerdict(p);
    return `| \`${p.id}\` | ${p.kind} | ${p.family} | ${p.colors.length} | ${yes(r.monotone)} | ${r.minDeltaL.toFixed(3)} | ${light} | ${r.hueSpread}° | ${yes(r.ok)} | ${verdict} |`;
  });
  return [
    `| Ramp | Kind | Family | Stops | Monotone L | Min ΔL | Light end (${SURFACES.join(' / ')}) | Hue spread | Ordinal ok | Verdict |`,
    '|---|---|---|---|---|---|---|---|---|---|',
    ...rows,
  ].join('\n');
}

/** One row per family: palettes by kind and the flags of its categorical sets. */
export function familyTable(palettes: readonly Palette[], families: readonly PaletteFamily[]): string {
  const byId = new Map(palettes.map((p) => [p.id, p]));
  const rows = families.map((f) => {
    const ps = f.paletteIds.map((id) => byId.get(id)).filter((p): p is Palette => p !== undefined);
    const of = (kind: Palette['kind']): string => ps.filter((p) => p.kind === kind).map((p) => `\`${p.id}\``).join(' ') || '—';
    const cats = ps.filter((p) => p.kind === 'categorical');
    const flags = cats.length ? cats.map((p) => (p.labelsRequired ? 'labels' : p.colorblindSafe ? 'cvd-safe' : 'pass')).join(' ') : '—';
    return `| ${f.id} | ${f.label} | ${ps.length} | ${of('categorical')} | ${of('sequential')} | ${of('diverging')} | ${flags} |`;
  });
  return [
    '| Family | Label | Palettes | Categorical | Sequential | Diverging | Categorical flags |',
    '|---|---|---|---|---|---|---|',
    ...rows,
  ].join('\n');
}

/** The whole generated block, markers included, for PALETTES.md §7. */
export function renderValidationReport(palettes: readonly Palette[], families: readonly PaletteFamily[]): string {
  const counts = (['categorical', 'sequential', 'diverging'] as const).map((k) => `${palettes.filter((p) => p.kind === k).length} ${k}`).join(', ');
  return [
    REPORT_BEGIN,
    `Registry: **${palettes.length} palettes** (${counts}) in ${families.length} families; surfaces ${SURFACES.join(' and ')}.`,
    '',
    '### Families',
    '',
    familyTable(palettes, families),
    '',
    '### Categorical sets',
    '',
    categoricalTable(palettes),
    '',
    '### Ramps (stepped form)',
    '',
    rampTable(palettes),
    REPORT_END,
  ].join('\n');
}

/** The generated block of a PALETTES.md source, markers included; null when the markers are missing. */
export function extractReport(markdown: string): string | null {
  const a = markdown.indexOf(REPORT_BEGIN);
  const b = markdown.indexOf(REPORT_END);
  return a >= 0 && b > a ? markdown.slice(a, b + REPORT_END.length) : null;
}
